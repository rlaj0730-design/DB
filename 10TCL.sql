/*==============================================================================

    1. TCL이란?
    트랜잭션을 제어하는 명령어이다.
    
    2. 트랜잭션이란?
    하나의 작업을 처리하기 위해 실행되는 여러 SQL 작업의 묶음이다.
    
    3. TCL의 명령어
    - COMMIT   : 변경 내용을 확정하고 저장시켜준다.
    - ROLLBACK : 변경 내용을 취소하고 이전 상태로 되돌려준다.

==============================================================================*/

-- 예)
-- 1. 연구개발팀의 이름 변경
-- 2. 매니저ID 변경
-- 3. 모든 작업이 정상적으로 끝나면 COMMIT

SELECT *
  FROM 부서;
  
-- 연구개발팀의 이름을 AI연구개발팀으로 변경
  
UPDATE 부서
   SET 부서이름 = 'AI연구개발팀'
 WHERE 부서ID = 1;

COMMIT; -- 저장시킨다.

-- 부서라는 테이블에서 기획팀을 AI기획팀으로 변경해보자!
UPDATE 부서
   SET 부서이름 = 'AI기획팀';
   
SELECT *
  FROM 부서;
  
ROLLBACK; -- 되돌린다.

/*==============================================================================
    2. 트랜잭션의 4가지 특성
    - 원자성, 일관성, 고립성, 지속성
    
    - 원자성 : 모든 작업이 성공하거나, 모두 취소가 되어야 한다.
    - 일관성 : 작업 전후의 데이터가 올바른 상태를 유지해야 한다.
    - 고립성 : 작업 중인 데이터는 다른 작업의 영향을 받으면 안된다.
    - 지속성 : COMMIT을 한 데이터는 DB에 계속 저장이 되어야 한다.
==============================================================================*/

/*==============================================================================
    3. LOCK
    - 한 세션이 어떤 데이터를 변경하고 있을 때
    - 다른 세션이 같은 데이터를 동시에 변경하지 못하도록 막는 것이다!
==============================================================================*/

/*==============================================================================
    4. SESSION
    - 데이터베이스에 접속되어 있는 하나의 연결 상태이다.
==============================================================================*/


/* ============================================================================
   5. 오늘 정리
============================================================================ */

-- TCL         : 트랜잭션을 제어하는 명령어
-- 트랜잭션    : 하나의 작업으로 처리하는 SQL 작업들의 묶음
-- COMMIT      : 변경 내용 확정 및 저장
-- ROLLBACK    : COMMIT하지 않은 변경 내용 취소
-- SESSION     : DB에 접속된 하나의 연결 상태
-- LOCK        : 같은 데이터를 동시에 변경하지 못하도록 막는 것

-- ★ 핵심
-- COMMIT하기 전에는 ROLLBACK으로 변경 내용을 취소할 수 있습니다.
-- COMMIT한 내용은 ROLLBACK으로 되돌릴 수 없습니다.


