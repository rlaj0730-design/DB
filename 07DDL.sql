-- [기본 문법] ALTER TABLE 테이블명 
--            ADD CONSTRAINT 제약조건이름 
--            제약조건종류 (컬럼명);
-- 제약조건이름은 보통 "테이블명_컬럼명_종류" 형태로 짓습니다. (읽었을 때 뭔지 바로 알 수 있게)

-- 직원ID는 직원을 한 명씩 구분하는 대표 번호입니다.
ALTER TABLE 직원
ADD CONSTRAINT 직원_직원ID_PK
PRIMARY KEY (직원ID);

-- 서로 다른 직원이 같은 이메일을 사용하지 못하게 할거다.
-- 할때 UNIQUE사용. -> NULL을 허용하지만, 중복된 값은 절대 불가능!
ALTER TABLE 직원
ADD CONSTRAINT 직원_이메일_UK  --유니크도 키라서 UK로 표시
UNIQUE (이메일);               -- 제약 조건은 테이블명_컬럼명_?K 형태로 작성

-- 급여 컬럼을 수정해보자.
-- CHECK
ALTER TABLE 직원
ADD CONSTRAINT 직원_급여_CK  
CHECK (급여 > 0);
-- 이제 급여에 -5000같은 값을 넣으려고 하면 오류가 난다!

-- 테이블 삭제
-- 정말 주의해서 사용해야 한다.(아주아주아주 큰일날수있음 현업에서)
DROP TABLE 네이버회원;


