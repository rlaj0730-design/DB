-- CREATE TABLE : 새로운 테이블 만들기
-- 제약조건     : 잘못된 데이터가 들어오는 것을 막는 규칙
-- PRIMARY KEY : 각 행을 구분하는 대표 값
-- FOREIGN KEY : 다른 테이블에 존재하는 값을 참조하는 연결 규칙
-- ALTER TABLE  : 기존 테이블의 구조 수정하기
-- DROP TABLE   : 테이블 자체를 삭제하기

-- 오늘 가장 중요한 네 문장
-- 1. CREATE는 테이블을 만듭니다.
-- 2. 제약조건은 잘못된 데이터를 막습니다.
-- 3. ALTER는 만들어진 테이블을 수정합니다.
-- 4. DROP은 테이블 자체를 삭제합니다.

-- 테이블명과 컬럼명에는 띄어쓰기를 사용하지 않는 것이 좋습니다.
-- 띄어쓰기가 필요하면 큰따옴표(" ")로 만들 수 있지만,
-- 사용할 때마다 큰따옴표를 써야 해서 일반적으로 사용하지 않습니다.





