   4. 제약조건
============================================================================ */

-- [왜 필요할까?] 제약조건이 하나도 없다면 이런 일이 생길 수 있습니다.
-- - 급여 컬럼에 실수로 마이너스(-500) 값을 넣어버림
-- - 직원ID가 100인 사람이 두 명 생겨서 누가 누군지 구분이 안 됨
-- - 부서ID가 999인 직원을 넣었는데, 정작 999번 부서는 존재하지 않음
-- 이런 "말이 안 되는 데이터"가 애초에 들어오지 못하게 막아주는 규칙이 제약조건입니다.

-- 제약조건은 잘못된 데이터가 테이블에 들어오는 것을 막는 규칙입니다.
-- NOT NULL    : 반드시 값을 입력해야 합니다.
-- CHECK       : 정해 놓은 조건에 맞는 값만 입력할 수 있습니다.
-- UNIQUE      : 같은 값을 중복해서 입력할 수 없습니다.
-- PRIMARY KEY : 각 행을 구분하는 대표 값으로, NULL과 중복이 불가능합니다. => 기본키(둘다 시험에 많이 나옴)
-- FOREIGN KEY : 다른 테이블에 실제로 존재하는 값만 참조할 수 있습니다.    => 참조키(//)

-- 무결성
-- 데이터가 틀리지 않고 서로 앞뒤가 맞는 상태를 말합니다.

-- 개체 무결성
-- PRIMARY KEY는 NULL이거나 중복될 수 없습니다.
-- (비유: 주민등록번호처럼, 한 사람을 딱 구분해주는 값은 비어있거나 겹치면 안 됩니다)

-- 참조 무결성
-- FOREIGN KEY에는 부모 테이블에 존재하지 않는 값을 넣을 수 없습니다.
-- (비유: 존재하지 않는 학번을 출석부에 적을 수 없는 것과 같습니다.
--  "직원"의 부서ID는 반드시 "부서" 테이블에 실제로 있는 부서ID여야 합니다)

CREATE TABLE 네이버회원 (
    ID          VARCHAR2(15),
    이름        VARCHAR2(12) NOT NULL,
    비밀번호    VARCHAR2(16),
    생년월일    DATE,
    성별        VARCHAR2(3)
);

-- ALTER는 이미 만들어진 테이블의 구조를 수정할 때 사용한다.
-- ADD(추가) / MODIFY(변경) / RENAME COLUMN(이름 변경) / DROP COLUMN(삭제)
-- 1단계. 네이버회원 테이블에 닉네임 컬럼을 추가해보자.
ALTER TABLE 네이버회원
ADD 닉네임 VARCHAR2(20);

-- 2단계. 닉네임 컬럼의 크기를 20바이트에서 30바이트로 늘려보자.
-- 변경 : MODIFY
ALTER TABLE 네이버회원
MODIFY 닉네임 VARCHAR2(30);

-- 3단계. 닉네임 컬럼의 이름을 별명으로 변경해보자.
-- 컬럼명 변경 : RENAME COLUMN
ALTER TABLE 네이버회원
RENAME COLUMN 닉네임 TO 별명;

-- 4단계. 방금 만든 별명 컬럼을 삭제해보자.
-- 삭제 : DROP COLUMN
ALTER TABLE 네이버회원
DROP COLUMN 별명;

