/* ============================================================================
   1. DDL이란?
============================================================================ */

-- 지금까지 배운 SELECT는 이미 만들어진 테이블에서 데이터를 조회합니다.
-- DDL은 데이터를 담을 테이블의 구조를 만들거나, 수정하거나, 삭제합니다.
-- 여기서부터 정보처리 기사에 많이 나옴(EX DDL에 속하지 않는 명령어는?)

-- CREATE : 새로운 ~ 만들기. (테이블, 유저, ....)
-- ALTER  : 만들어진 테이블을 수정할 때 사용
-- RENAME : 테이블 또는 컬럼의 이름을 변경할 때 사용
-- TRUNCATE : 테이블은 남기는 대신에 테이블 안에 있는 데이터는 모두 삭제할 때 사용
-- DROP   : 테이블 자체를 삭제할 때 사용

-- 비유로 이해하기 : SELECT가 "이미 지어진 집 안을 구경하는 것"이라면,
-- DDL은 "집을 짓거나(CREATE), 방을 새로 만들거나 고치거나(ALTER), 아예 허무는 것(DROP)"입니다.

-- 한 문장 정리
-- DDL(Data Definition Language)은 데이터베이스의 구조를 다루는 명령어입니다.

/* ============================================================================
   2. Oracle 주요 자료형
============================================================================ */

-- VARCHAR2(크기) : 이름, 이메일처럼 길이가 달라지는 문자 저장
-- CHAR(크기)     : 성별 코드처럼 길이가 일정한 문자 저장
-- NUMBER         : 나이, 급여처럼 숫자 저장
-- DATE           : 생년월일, 입사일처럼 날짜와 시간 저장
-- CLOB           : 게시글처럼 매우 긴 문자 저장
-- BLOB           : 이미지, 영상, 파일 같은 데이터 저장

-- NUMBER(전체 자릿수, 소수점 아래 자릿수)
-- NUMBER(6)   : 최대 6자리 정수(소수점은 무한. 그래서 실수는 아래꺼 씀)
-- NUMBER(8,2) : 전체 8자리 중 소수점 아래 2자리 (예: 123456.78)

-- VARCHAR2(최대 크기)
-- VARCHAR2(20 BYTE) : 최대 20바이트까지 저장
-- 영문 1글자 ≈ 1바이트
-- 한글 1글자 ≈ 3바이트

-- 예시
-- VARCHAR2(20 BYTE)
-- 영문은 최대 약 20글자
-- 한글은 최대 약 6글자

-- VARCHAR2(20 CHAR)
-- BYTE가 아니라 글자 수를 기준으로 저장
-- 영문/한글 상관없이 최대 20글자

/* ============================================================================
   3. CREATE TABLE
   
   -- CREATE TABLE은 데이터를 저장할 새로운 빈 표를 만드는 명령어이다.
   
   기본 문법
   CREATE TABLE 테이블명(
          컬럼명 자료형,
          컬럼명 자료형
    );
            
    테이블을 만들 때 정하는 것
    1. 테이블 이름
    2. 컬럼 이름
    3. 각 컬럼에 저장할 자료형
    4. 필요한 경우에 제약조건
    
    테이블 생성 규칙
    1. 같은 사용자의 테이블 이름은 중복될 수 없습니다.
    2. 같은 테이블 안에서 컬럼 이름은 중복될 수 없습니다.
    3. 테이블과 컬럼 이름은 문자로 시작하는 것이 안전합니다.(파이썬 변수 지정과 마찬가지로)
    4. SELECT, FROM 같은 Oracle 예약어는 이름으로 사용하지 않습니다.
    5. 읽기 어려운 특수문자와 공백은 사용하지 않는 것이 좋습니다.
    
    
============================================================================ */

-- 직원 테이블 만들기
CREATE TABLE 직원(
    직원ID NUMBER(6) NOT NULL, -- 널이없다. 무조건 직원아이디 데이터를 넣어야 한다는 뜻
    이름 VARCHAR2(20),         -- NOT NULL들어간 부분이 제약조건이다. 그래서 이름은 널값 넣어도 된다는 뜻
    성          VARCHAR2(25)  NOT NULL,
    이메일      VARCHAR2(25)  NOT NULL,
    핸드폰      VARCHAR2(20),
    입사일      DATE          NOT NULL,
    직업ID      VARCHAR2(10)  NOT NULL,
    급여        NUMBER(8,2),
    수수료비율  NUMBER(2,2),
    매니저ID    NUMBER(6),
    부서ID      NUMBER(4)
);

SELECT *
FROM 직원;

