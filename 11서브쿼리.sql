/*==============================================================================

    1. 서브쿼리란?
    SELECT문 안에 또 다른 SELECT문이 괄호로 들어있는 것
    안쪽 괄호가 먼저 실행이 되고 바깥쪽 SELECT문이 조회를 해준다.(파이썬과 비슷)
    
