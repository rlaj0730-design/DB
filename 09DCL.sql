/* ============================================================================
   1. DCL이 뭐야?
============================================================================ */

-- DCL = 누구한테 무엇을 허락할지 정하는 명령어.
--
-- GRANT  = 권한을 "준다"
-- REVOKE = 권한을 "빼앗는다"
--
-- 그게 다입니다. 오늘은 이 두 개만 잘 쓰면 됩니다.


/* ============================================================================
   2. 전체 순서 미리보기 (이 순서대로만 따라가면 됩니다)
============================================================================ */

-- 1) SYSTEM 계정으로 DCLTEST 계정을 만든다        -> Run SQL Command Line
-- 2) DCLTEST가 로그인할 수 있게 권한을 준다        -> Run SQL Command Line (SYSTEM)
-- 3) hr 계정으로 접속해서, DCLTEST에게 직원 테이블 보는 권한을 준다  -> SQL Developer (hr)
-- 4) DCLTEST로 접속해서 진짜 되는지 확인한다        -> SQL Developer (DCLTEST)

-- 도구가 헷갈리면 이렇게만 기억하세요.
-- "계정 만들기 / 로그인 권한 주기" = 검은 화면(Run SQL Command Line), SYSTEM 계정
-- "그 다음부터"는 우리가 늘 쓰던 SQL Developer


/* ============================================================================
   1단계. DCLTEST 계정 만들기
============================================================================ */

-- Run SQL Command Line 열고, SYSTEM 계정으로 접속합니다.
-- (비밀번호는 예시일 뿐, chani님 컴퓨터에 설정된 실제 SYSTEM 비밀번호를 쓰세요)

CONN SYSTEM/12345;

-- 새 계정을 만듭니다. DCLTEST가 계정 이름, 12345가 그 계정의 비밀번호입니다.
CREATE USER DCLTEST IDENTIFIED BY 12345;
                    -- 아이덴티파이드

-- 여기까지 하면 DCLTEST라는 "이름표"만 생긴 상태입니다.
-- 아직 아무것도 할 수 없는 상태예요. (로그인조차 안 됨)


/* ============================================================================
   2단계. 로그인할 수 있게 권한 주기
============================================================================ */

-- 아직도 SYSTEM 계정 상태 그대로, 이어서 입력합니다.

GRANT CREATE SESSION TO DCLTEST;

-- 이 한 줄이 하는 일 : "DCLTEST야, 이제 로그인은 해도 돼"
-- 이걸 안 하면 DCLTEST로 접속하려고 할 때
-- ORA-01045: user DCLTEST lacks CREATE SESSION privilege 라는 오류가 납니다.


/* ============================================================================
   3단계. hr의 직원 테이블을 볼 수 있게 권한 주기
============================================================================ */

-- 여기서부터는 도구를 바꿉니다!
-- SQL Developer를 열고, hr 계정으로 접속하세요. (지금까지 실습해온 그 계정)
--
-- 왜 SYSTEM이 아니라 hr로 접속해야 할까?
-- EMPLOYEES(직원) 테이블은 hr 계정의 소유물이기 때문에,
-- 그 테이블에 대한 권한은 주인인 hr만 남에게 줄 수 있습니다.

GRANT SELECT, UPDATE
ON HR.EMPLOYEES
TO DCLTEST;

-- 이 한 줄이 하는 일 : "DCLTEST야, 내 직원 테이블 봐도 되고 고쳐도 돼"


/* ============================================================================
   4단계. 진짜 되는지 확인하기
============================================================================ */

-- SQL Developer에서 이번엔 DCLTEST 계정으로 새로 접속해보세요.
--
-- 접속이 잘 되면 2단계 성공.
-- 그 상태에서 아래 SQL을 실행해보세요. 계정 이름을 앞에 꼭 붙여야 합니다.
-- (내 계정이 아닌 hr 계정 소유 테이블이라서 "누구 것인지" 표시가 필요합니다)

SELECT * FROM HR.EMPLOYEES;

-- 데이터가 잘 보이면 3단계도 성공입니다!


/* ============================================================================
   3. (참고) 권한을 다시 뺏고 싶을 때
============================================================================ */

-- REVOKE는 GRANT의 반대입니다. SYSTEM 계정으로 실행합니다.

-- REVOKE CREATE SESSION FROM DCLTEST;
-- 위처럼 하면 DCLTEST는 다시 로그인이 안 됩니다.


/* ============================================================================
   4. 오늘 정리
============================================================================ */

-- GRANT 권한 TO 계정   : 권한을 준다
-- REVOKE 권한 FROM 계정 : 권한을 뺏는다
--
-- 오늘 준 권한 2가지
-- 1. CREATE SESSION      -> "로그인 자체"를 할 수 있는 권한
-- 2. SELECT, UPDATE ON ~ -> "특정 테이블 하나"를 보고 고칠 수 있는 권한
--
-- 꼭 기억할 것
-- 권한은 자동으로 따라오지 않습니다. 계정을 만들어도, 그 계정으로
-- "뭘 할 수 있는지"는 하나하나 GRANT로 직접 열어줘야 합니다.

